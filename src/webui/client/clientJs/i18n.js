function getInitialLanguage() {
  try {
    const stored = localStorage.getItem('evolver.webui.language');
    if (I18N_LANGS.includes(stored)) return stored;
  } catch (_) { /* localStorage may be unavailable */ }
  const browserLang = (navigator.language || '').toLowerCase();
  if (browserLang.startsWith('zh')) return 'zh';
  if (browserLang.startsWith('ja')) return 'ja';
  return 'en';
}

function t(key, vars = {}, fallback) {
  const dict = I18N[state.lang] || I18N.en;
  let text = dict[key] ?? I18N.en[key] ?? fallback;
  if (text == null) return key;
  return String(text).replace(/\\{(\\w+)\\}/g, (_, name) => vars[name] ?? '');
}

function valueLabel(value) {
  if (value === null || value === undefined || value === '') return '-';
  if (typeof value === 'boolean') return t('value.' + String(value), {}, String(value));
  if (typeof value !== 'string') return value;
  const normalized = value.toLowerCase().replace(/[\\s-]+/g, '_');
  return t('value.' + normalized, {}, value);
}

function categoryLabel(value) {
  return t('category.' + value, {}, value);
}

function validationLabel(value) {
  return t('validation.' + value, {}, value);
}

function assetKindLabel(kind) {
  return t('asset.' + kind, {}, kind);
}

function tableHeader(keys) {
  return '<thead><tr>' + keys.map((key) => '<th>' + esc(t(key)) + '</th>').join('') + '</tr></thead>';
}

function applyStaticTranslations() {
  document.documentElement.lang = I18N_HTML_LANG[state.lang] || 'en';
  document.title = t('app.title');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'), {}, el.textContent);
  });
  document.querySelectorAll('.language-option').forEach((btn) => {
    const active = btn.getAttribute('data-lang') === state.lang;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });
}

function setLanguage(lang, opts = {}) {
  if (!I18N_LANGS.includes(lang)) return;
  state.lang = lang;
  try { localStorage.setItem('evolver.webui.language', lang); } catch (_) {}
  applyStaticTranslations();
  if (typeof renderVersionCard === 'function') renderVersionCard(state.versionInfo);
  if (typeof renderVersionModal === 'function' && $('version-modal') && !$('version-modal').hidden) renderVersionModal(state.versionInfo);
  if (opts.refresh !== false && typeof refresh === 'function') refresh();
}

function initializeLanguageControls() {
  state.lang = getInitialLanguage();
  applyStaticTranslations();
  document.querySelectorAll('.language-option').forEach((btn) => {
    btn.addEventListener('click', () => setLanguage(btn.getAttribute('data-lang')));
  });
}
